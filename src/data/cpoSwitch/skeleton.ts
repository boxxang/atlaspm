/**
 * /data/cpoSwitch/skeleton.ts — the shape of the CPO Network Switch System
 * template: its stages, when each runs, the gate each closes on, and the
 * activities inside each one with their owner and window.
 *
 * A co-packaged-optics switch is not one chip. It is a switching ASIC, the
 * high-speed I/O silicon beside it, the electrical ICs that drive and receive
 * the optics, the photonic ICs, an optical source, a bridge or interposer,
 * silicon capacitors, an advanced package that carries all of them plus the
 * fiber, a system board, a cooling solution, firmware and software — and a
 * factory that can calibrate and test the result. The template follows the
 * product, not the parts: stages are the program's lifecycle, each closing on
 * a gate every workstream has to reach together, and the components and
 * disciplines run as parallel activities inside them. So the package is
 * designed while the RTL is written, the test hardware is built before the
 * wafers exist, and the firmware is running on emulation before first silicon.
 *
 * Bring-up is split where the program actually reports it — first electrical
 * link, first optical link, first end-to-end traffic, full bandwidth — because
 * those are the dates a CPO program is held to, and a milestone here is the
 * end of a stage.
 *
 * This module is the contract the stage modules beside it are written to; a
 * test holds every one of them to it. Weeks are from kickoff; activity windows
 * are weeks from their stage's start. Generic throughout: no vendor, product
 * or standard revision is named.
 */

export type CpoBand = 'define' | 'enable' | 'designVerify' | 'implement' | 'manufacture' | 'integrate' | 'validateRamp';

export interface CpoActivitySkeleton {
  ref: string;
  title: string;
  /** the role that owns it — one of CPO_OWNERS */
  owner: string;
  /** [from, to] weeks from the stage start */
  w: [number, number];
}

export interface CpoStageSkeleton {
  key: string;
  /** the activity and deliverable prefix, and the short title */
  prefix: string;
  title: string;
  band: CpoBand;
  start: number;
  dur: number;
  gate: { id: string; label: string; major?: boolean };
  activities: CpoActivitySkeleton[];
}

